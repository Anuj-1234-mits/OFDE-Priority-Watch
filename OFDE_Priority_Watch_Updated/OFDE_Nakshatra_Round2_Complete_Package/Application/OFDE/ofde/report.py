"""HTML and CSV report generation. Every number comes from the stored analysis record, formatted by the
same helpers the tests use, so reports cannot differ from what the API returned."""
from __future__ import annotations

import csv
import html
import io
import json

from . import __version__


def f(x, nd=3, unit=""):
    """Format a number; None -> 'unavailable' (unknown is never shown as zero)."""
    if x is None:
        return "unavailable"
    return f"{x:.{nd}f}{(' ' + unit) if unit else ''}"


def esc(x) -> str:
    return html.escape("" if x is None else str(x), quote=True)


def _row(*cells):
    return "<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>"


def report_html(rec: dict) -> str:
    ds = rec["dataset"]
    scen = rec["scenarios"]
    w = rec["window"]
    sw = rec["software"]
    parts = []
    add = parts.append
    synthetic = ds["origin"] == "synthetic"
    add("<!doctype html><html lang='en'><head><meta charset='utf-8'>")
    # The report is static: forbid scripts, remote loads and forms even if a user-supplied string slipped through escaping.
    add("<meta http-equiv='Content-Security-Policy' content=\"default-src 'none'; style-src 'unsafe-inline'; img-src data:\">")
    add(f"<title>OFDE report - {esc(rec['title'])}</title>")
    add("<style>body{font-family:Segoe UI,Arial,sans-serif;max-width:980px;margin:2rem auto;padding:0 1rem;color:#14202e;line-height:1.5}"
        "table{border-collapse:collapse;width:100%;margin:.5rem 0 1.5rem}td,th{border:1px solid #b9c4d0;padding:.35rem .5rem;text-align:left;vertical-align:top;font-size:.92rem}"
        "th{background:#e8eef4}.banner{border:2px solid #b45309;background:#fff7ed;padding:.6rem 1rem;margin:1rem 0}code,pre{font-family:Consolas,monospace;font-size:.85rem}"
        "pre{background:#f1f5f9;padding:.6rem;overflow:auto}h2{border-bottom:1px solid #b9c4d0;padding-bottom:.2rem;margin-top:2rem}"
        "@media print{body{max-width:none;margin:0;color:#000;font-size:11pt}.banner{border-width:1px;break-inside:avoid}tr{break-inside:avoid}h2,h3{break-after:avoid}"
        "pre{white-space:pre-wrap;word-break:break-all;overflow:visible}table{font-size:9.5pt}}</style></head><body>")
    add(f"<h1>{esc(rec['title'])}</h1>")
    add(f"<p>Generated by OFDE {esc(__version__)} &middot; analysis #{esc(rec.get('id'))} &middot; created {esc(rec['created_utc'])}</p>")
    add("<div class='banner'><strong>Research and educational prototype.</strong> Not a certified collision-avoidance or "
        "conjunction-assessment product. Values are computed from TLE mean elements and do not include covariance; no collision probability is given.</div>")
    if synthetic:
        add("<div class='banner'><strong>SYNTHETIC DEMONSTRATION DATA.</strong> The objects in this analysis are fictitious. "
            "Results do not describe any real satellite or debris event.</div>")
    ver = sw["sgp4_verification"]
    add(f"<div class='banner'>Propagation verification on the machine that produced this report: "
        f"<strong>{'verified' if ver.get('verified') else 'NOT verified'}</strong>"
        f"{'' if ver.get('verified') else ' (' + esc(ver.get('reason')) + ')'}</div>")

    add("<h2>1. Dataset provenance</h2><table>")
    for k, v in (("Dataset", ds["name"]), ("Origin", ds["origin"]), ("Source description", ds["source_description"]),
                 ("Filename", ds.get("filename")), ("Format", ds["format"]), ("Imported (UTC)", ds["imported_utc"]),
                 ("Units / frame assumptions", ds["units_frame_assumptions"]), ("Validation outcome", ds["validation"]["outcome"])):
        add(_row(esc(k), esc(v if v is not None else "not recorded")))
    add("</table>")

    add("<h2>2. Objects and input validation</h2><table><tr><th>Role</th><th>ID</th><th>Name</th><th>Type</th><th>TLE epoch (UTC)</th><th>Validation messages</th></tr>")
    for role in ("a", "b"):
        o = rec["objects"][role]
        msgs = "; ".join(f"{i['severity']}: {i['message']}" for i in o["issues"]) or "none"
        add(_row(role.upper(), esc(o["object_id"]), esc(o["name"] or "unknown"), esc(o["object_type"] or "unknown"),
                 esc(o["tle"]["epoch_utc"]), esc(msgs)))
    add("</table>")

    add("<h2>3. Analysis interval and assumptions</h2><table>")
    isum = rec.get("input_summary")
    extra = []
    if isum:
        extra = [("TLE epoch A / B (UTC)", f"{isum['epoch_a_utc']} / {isum['epoch_b_utc']}"),
                 ("Epoch difference B minus A", f"{isum['epoch_difference_s']:.3f} s")]
    for k, v in (*extra, ("Window start (UTC)", w["start_utc"]), ("Duration", f"{w['duration_s']} s"), ("Grid step", f"{w['step_s']} s"),
                 ("Refinement tolerance", f"{w['tol_s']} s"), ("Frame", scen[0]["result"]["frame"]),
                 ("Scope", "Closest approach within the analysed window only; not a guaranteed global minimum")):
        add(_row(esc(k), esc(v)))
    add("</table>")

    add("<h2>4. Calculation method and software</h2><table>")
    for k, v in (("Propagator", f"{scen[0]['propagator']['name']} {scen[0]['propagator']['version']}"),
                 ("OFDE version", sw["ofde"]), ("Python", sw["python"]), ("sgp4 package", sw["sgp4_version"] or "not installed"),
                 ("TCA method", "Uniform grid, local-minimum bracketing, golden-section refinement on squared separation"),
                 ("Request hash (SHA-256)", rec["reproducibility"]["request_sha256"]),
                 ("Result hash (SHA-256)", rec["reproducibility"]["result_sha256"])):
        add(_row(esc(k), esc(v)))
    add("</table>")

    add("<h2>5. Computed results by scenario</h2><table><tr><th>Scenario</th><th>Inputs changed</th><th>TCA (UTC)</th><th>Miss distance</th>"
        "<th>Relative speed</th><th>Time inside radius</th><th>Bracketed</th></tr>")
    for s in scen:
        r = s["result"]
        ch = "; ".join(f"{t.upper()}.{c['field']}: {c['original']} -> {c['new']} {c['unit']}" for t in ("a", "b") for c in s["changes"][t]) or "none (baseline)"
        dw = s["dwell"]
        dwtxt = "unavailable" if not dw else f"{f(dw['duration_s'], 3, 's')}{' (censored by window)' if dw['censored_low'] or dw['censored_high'] else ''} within {dw['radius_km']} km"
        add(_row(esc(s["name"]), esc(ch), esc(r["tca_utc"]), esc(f(r["miss_distance_km"], 3, "km")),
                 esc(f(r["rel_speed_km_s"], 3, "km/s")), esc(dwtxt), "yes" if r["bracketed"] else "NO (edge of window)"))
    add("</table>")

    add("<h2>6. Baseline versus alternatives (Threat Transfer)</h2>")
    if rec["comparison"]:
        add("<table><tr><th>Alternative</th><th>TT (km)</th><th>TT relative</th><th>&Delta;TCA (s)</th><th>&Delta;relative speed (km/s)</th></tr>")
        for c in rec["comparison"]:
            t = c["threat_transfer"]
            add(_row(esc(c["name"]), esc(f(t["tt_km"], 3)), esc(f(t["tt_rel"], 4)), esc(f(t["delta_tca_s"], 3)), esc(f(t["delta_rel_speed_km_s"], 5))))
        add("</table><p>TT_km = d_baseline &minus; d_alternative; positive means the alternative is closer. Project-defined metric.</p>")
    else:
        add("<p>No alternative scenarios were defined.</p>")

    add("<h2>7. Future Exposure Index (project-defined, not a probability)</h2>")
    fe = rec["fei"]
    add(f"<p>Parameters: {esc(json.dumps(fe['params']))}</p><table><tr><th>Rank</th><th>Scenario</th><th>Miss (km)</th><th>Dwell (s)</th><th>Closeness</th><th>Dwell term</th><th>FEI</th></tr>")
    for r in fe["ranking"]:
        add(_row(r["rank"], esc(r["name"]), esc(f(r["miss_distance_km"], 3)), esc(f(r["dwell_s"], 3)), esc(f(r["closeness"], 4)), esc(f(r["dwell_term"], 4)), esc(f(r["fei"], 2))))
    add("</table>")
    if fe["unranked"]:
        add("<p>Not ranked (missing data): " + esc(", ".join(f"{u['name']} ({u['reason']})" for u in fe["unranked"])) + "</p>")

    add("<h2>8. Decision Sensitivity experiments</h2>")
    if rec["sensitivity"]:
        add("<p>These are <strong>sensitivity experiments</strong> using hypothetical perturbations of TLE fields. They are not validated uncertainty estimates: no covariance was available.</p>")
        for sx in rec["sensitivity"]:
            t = sx["miss_table"]
            add(f"<h3>Object {esc(sx['target'].upper())}: {esc(sx['parameter'])} ({esc(t['parameter_unit'])})</h3>")
            add("<table><tr><th>Parameter value</th><th>Miss distance (km)</th><th>&Delta; miss (km)</th><th>Slope (km per unit)</th><th>TCA offset (s)</th></tr>")
            for row, trow in zip(t["rows"], sx["tca_table"]["rows"]):
                add(_row(esc(f(row["p"], 4)), esc(f(row["y"], 3)), esc(f(row["delta_y"], 3)), esc(f(row["slope"], 4)), esc(f(trow["y"], 3))))
            add(f"</table><p>Least-squares slope over the range: {esc(f(t['least_squares_slope'], 4))} km per {esc(t['parameter_unit'])}; range of miss distance: {esc(f(t['output_range'], 3))} km.</p>")
    else:
        add("<p>No sensitivity sweeps were requested. Monte Carlo / covariance propagation is unavailable (no covariance in TLE input).</p>")

    add("<h2>9. Metric definitions</h2><ul>"
        "<li><strong>Threat Transfer</strong>: TT_km = d_b &minus; d_k; TT_rel = TT_km / d_b. Project-defined.</li>"
        "<li><strong>FEI</strong>: 100 &middot; (w_d&middot;c_d + w_t&middot;c_t)/(w_d+w_t); c_d = d_ref/(d_ref+d); c_t = min(1, T/t_ref). Project-defined, comparative only.</li>"
        "<li><strong>Decision Sensitivity</strong>: finite-difference slope of an output with respect to a perturbed input. Project-defined.</li></ul>")

    add("<h2>10. Warnings and limitations</h2><ul>")
    for wmsg in rec["warnings"]:
        add(f"<li>{esc(wmsg)}</li>")
    for lim in rec["limitations"]:
        add(f"<li>{esc(lim)}</li>")
    add("</ul>")

    add("<h2>11. Reproducibility record</h2><p>Re-submitting this request to the same OFDE/sgp4 versions reproduces these results.</p>")
    add(f"<pre>{esc(json.dumps(rec['reproducibility']['request'], indent=2, sort_keys=True))}</pre>")
    add("<h3>TLE lines used per scenario</h3><pre>")
    for s in scen:
        add(esc(f"[{s['name']}]\n{s['tle_a']['line1']}\n{s['tle_a']['line2']}\n{s['tle_b']['line1']}\n{s['tle_b']['line2']}\n\n"))
    add("</pre></body></html>")
    return "".join(parts)


def scenarios_csv(rec: dict) -> str:
    buf = io.StringIO()
    wr = csv.writer(buf, lineterminator="\n")
    wr.writerow(["# OFDE scenario results", f"analysis_id={rec.get('id')}", f"dataset_origin={rec['dataset']['origin']}",
                 "units: distance km, speed km/s, time s / UTC"])
    wr.writerow(["scenario_id", "name", "inputs_changed", "tca_utc", "tca_offset_s", "miss_distance_km", "rel_speed_km_s",
                 "dwell_s", "dwell_radius_km", "bracketed", "frame", "propagator"])
    for s in rec["scenarios"]:
        r = s["result"]
        ch = "; ".join(f"{t.upper()}.{c['field']}: {c['original']} -> {c['new']} {c['unit']}" for t in ("a", "b") for c in s["changes"][t]) or "none"
        dw = s["dwell"]
        wr.writerow([s["id"], s["name"], ch, r["tca_utc"], r["tca_offset_s"], r["miss_distance_km"], r["rel_speed_km_s"],
                     "" if not dw else dw["duration_s"], "" if not dw else dw["radius_km"], r["bracketed"], r["frame"],
                     f"{s['propagator']['name']} {s['propagator']['version']}"])
    wr.writerow([])
    wr.writerow(["# FEI (project-defined; not a probability)", json.dumps(rec["fei"]["params"])])
    wr.writerow(["rank", "scenario", "miss_distance_km", "dwell_s", "closeness", "dwell_term", "fei"])
    for r in rec["fei"]["ranking"]:
        wr.writerow([r["rank"], r["name"], r["miss_distance_km"], r["dwell_s"], r["closeness"], r["dwell_term"], r["fei"]])
    return buf.getvalue()


def sensitivity_csv(rec: dict) -> str:
    buf = io.StringIO()
    wr = csv.writer(buf, lineterminator="\n")
    wr.writerow(["# OFDE sensitivity experiments (hypothetical perturbations; not validated uncertainty)"])
    wr.writerow(["target", "parameter", "parameter_unit", "parameter_value", "miss_distance_km", "delta_miss_km", "slope_km_per_unit", "tca_offset_s"])
    for sx in rec["sensitivity"]:
        t = sx["miss_table"]
        for row, trow in zip(t["rows"], sx["tca_table"]["rows"]):
            wr.writerow([sx["target"], sx["parameter"], t["parameter_unit"], row["p"], row["y"], row["delta_y"], row["slope"], trow["y"]])
    return buf.getvalue()
