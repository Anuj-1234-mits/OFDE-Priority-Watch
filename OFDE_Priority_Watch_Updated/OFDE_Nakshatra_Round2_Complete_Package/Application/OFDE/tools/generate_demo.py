"""Generate the SYNTHETIC demo dataset (data/demo_synthetic.json) and data/DESIGN_NOTES.md.

DESIGN AID ONLY. A plain two-body Kepler model (requires numpy) is used here solely to choose the
mean anomaly of the synthetic object B so that A and B have crossing orbits and a near pass inside
the demo window. The two-body numbers are NOT SGP4 results and are NOT used anywhere in the app.
The real miss distance/TCA are whatever the verified SGP4 pipeline computes on your machine.
Run (optional, output is already committed):  python tools/generate_demo.py
"""
import json
import math
import os
import sys
from datetime import datetime, timezone

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ofde.tle import format_tle, parse_tle  # noqa: E402

MU = 398600.4418  # km^3/s^2 (WGS-72 value 398600.8 differs negligibly for a design aid)
EPOCH = datetime(2026, 10, 24, 0, 0, 0, tzinfo=timezone.utc)


def n_from_a(a_km):  # rev/day
    return math.sqrt(MU / a_km ** 3) * 86400.0 / (2 * math.pi)


def kepler_pos(t_s, n_rev_day, ecc, inc, raan, argp, m0):
    n = n_rev_day * 2 * np.pi / 86400.0
    a = (MU / n ** 2) ** (1 / 3)
    M = np.radians(m0) + n * t_s
    E = M.copy()
    for _ in range(12):
        E = E - (E - ecc * np.sin(E) - M) / (1 - ecc * np.cos(E))
    x, y = a * (np.cos(E) - ecc), a * np.sqrt(1 - ecc ** 2) * np.sin(E)
    w, i, o = np.radians(argp), np.radians(inc), np.radians(raan)
    cw, sw, ci, si, co, so = np.cos(w), np.sin(w), np.cos(i), np.sin(i), np.cos(o), np.sin(o)
    X = (co * cw - so * sw * ci) * x + (-co * sw - so * cw * ci) * y
    Y = (so * cw + co * sw * ci) * x + (-so * sw + co * cw * ci) * y
    Z = (sw * si) * x + (cw * si) * y
    return np.stack([X, Y, Z], axis=-1)


OBJ = {
    "90001": dict(name="SYNTHETIC SAT-A", type="PAYLOAD", inc=74.0, raan=40.0, ecc=0.0001, argp=90.0, m0=0.0, a=6928.0, bstar=2.0e-5, des="26901A"),
    "90002": dict(name="SYNTHETIC DEBRIS-B", type="DEBRIS", inc=74.0, raan=100.0, ecc=0.0002, argp=20.0, m0=None, a=6931.0, bstar=3.0e-4, des="26901B"),
    "90003": dict(name="SYNTHETIC SAT-C", type="PAYLOAD", inc=98.2, raan=200.0, ecc=0.0010, argp=270.0, m0=120.0, a=7178.0, bstar=1.0e-5, des="26902A"),
    "90004": dict(name="SYNTHETIC DEBRIS-D", type="DEBRIS", inc=53.0, raan=310.0, ecc=0.0002, argp=45.0, m0=200.0, a=6778.0, bstar=2.0e-4, des="26903A"),
}


def main():
    a, b = OBJ["90001"], OBJ["90002"]
    t = np.arange(0, 14400.0, 10.0)
    na, nb = n_from_a(a["a"]), n_from_a(b["a"])
    pa = kepler_pos(t, na, a["ecc"], a["inc"], a["raan"], a["argp"], a["m0"])
    best = None
    for m0 in np.arange(0.0, 360.0, 0.02):
        pb = kepler_pos(t, nb, b["ecc"], b["inc"], b["raan"], b["argp"], m0)
        d = np.linalg.norm(pb - pa, axis=1)
        k = int(d.argmin())
        if 4500 <= t[k] <= 9500 and 0 < k < len(t) - 1 and (best is None or d[k] < best[0]):
            best = (float(d[k]), float(t[k]), float(m0))
    d_min, t_min, m0_b = best
    # fine pass: refine phase (0.0005 deg) and time (0.5 s) around the coarse optimum
    tf = np.arange(max(0.0, t_min - 60), t_min + 60, 0.5)
    paf = kepler_pos(tf, na, a["ecc"], a["inc"], a["raan"], a["argp"], a["m0"])
    best = (d_min, t_min, m0_b)
    for m0 in np.arange(m0_b - 0.06, m0_b + 0.06, 0.0005):
        pb = kepler_pos(tf, nb, b["ecc"], b["inc"], b["raan"], b["argp"], m0)
        d = np.linalg.norm(pb - paf, axis=1)
        k = int(d.argmin())
        if d[k] < best[0] or best[0] == d_min:
            if d[k] < best[0]:
                best = (float(d[k]), float(tf[k]), float(m0))
    d_min, t_min, m0_b = best
    b["m0"] = round(m0_b % 360.0, 4)
    lines, objects = [], {}
    for cat, o in OBJ.items():
        l1, l2 = format_tle(catalog=int(cat), intl_designator=o["des"], epoch=EPOCH, ndot=0.0, nddot=0.0, bstar=o["bstar"],
                            element_set=999, inclination_deg=o["inc"], raan_deg=o["raan"], eccentricity=o["ecc"],
                            arg_perigee_deg=o["argp"], mean_anomaly_deg=o["m0"], mean_motion_rev_per_day=n_from_a(o["a"]), rev_number=1)
        tle, issues = parse_tle(l1, l2, o["name"])
        assert tle is not None, issues
        lines += [o["name"], l1, l2]
        objects[cat] = {"name": o["name"], "object_type": o["type"], "synthetic": True,
                        "note": "Fictitious object. Catalog number is a placeholder and does not refer to any real object."}
    start = EPOCH.strftime("%Y-%m-%dT%H:%M:%SZ")
    demo = {
        "name": "OFDE synthetic demonstration set (fictitious objects)",
        "source_description": "SYNTHETIC. Generated by tools/generate_demo.py with a two-body design aid; elements are fictitious "
                              "and unrelated to any real satellite or debris object. Not real orbital observations.",
        "tle_text": "\n".join(lines) + "\n",
        "objects": objects,
        "cases": [
            {"id": "case-1", "object_a": "90001", "object_b": "90002", "description": "Designed crossing-orbit pair (same inclination, RAAN offset 60 deg, 3 km altitude difference)",
             "suggested_window": {"start_utc": start, "duration_s": 14400, "step_s": 30}},
            {"id": "case-2", "object_a": "90001", "object_b": "90004", "description": "Different-altitude pair, not designed to approach closely",
             "suggested_window": {"start_utc": start, "duration_s": 14400, "step_s": 30}},
            {"id": "case-3", "object_a": "90003", "object_b": "90002", "description": "Sun-synchronous-like orbit vs debris, not designed to approach closely",
             "suggested_window": {"start_utc": start, "duration_s": 14400, "step_s": 30}},
        ],
    }
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, "data", "demo_synthetic.json"), "w", encoding="utf-8") as fh:
        json.dump(demo, fh, indent=2)
    with open(os.path.join(root, "data", "DESIGN_NOTES.md"), "w", encoding="utf-8") as fh:
        fh.write(f"""# Demo dataset design notes (SYNTHETIC)

All four objects are fictitious. The set was generated by `tools/generate_demo.py`.

Design aid (two-body Kepler, **not SGP4**, **not a result**): with B's mean anomaly set to {b['m0']:.4f} deg, a two-body model
places A and B closest at about t = {t_min:.0f} s after the epoch ({start}), at a separation of about {d_min:.1f} km.
This was only used to pick orbit phasing so a close pass exists inside the 4-hour demo window.

The distance and time that OFDE reports come from SGP4 on your machine and will differ from these design numbers
(SGP4 includes J2, drag and other effects). Do not quote the design-aid numbers as a prediction.
""")
    print(f"design aid: B mean anomaly {b['m0']:.4f} deg; two-body closest approach ~{d_min:.2f} km at t={t_min:.0f} s")


if __name__ == "__main__":
    main()
